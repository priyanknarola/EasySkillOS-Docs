// ── Search Engine ────────────────────────────────────────────
function tokenize(text) {
  return text.toLowerCase()
    .replace(/[^a-z0-9\s\-\.\/]/g, ' ')
    .split(/\s+/)
    .filter(t => t.length > 1);
}

function scoreResult(item, queryTokens) {
  const titleTokens = tokenize(item.title);
  const bodyTokens  = tokenize(item.body);
  let score = 0;

  queryTokens.forEach(q => {
    // Exact title match — highest weight
    if (titleTokens.includes(q)) score += 10;
    // Title contains query — high weight
    else if (titleTokens.some(t => t.includes(q) || q.includes(t))) score += 6;
    // Body exact match
    bodyTokens.forEach(b => {
      if (b === q) score += 2;
      else if (b.includes(q) || q.includes(b)) score += 1;
    });
  });

  return score;
}

function search(query) {
  if (!query || query.trim().length < 2) return [];
  const queryTokens = tokenize(query);
  if (!queryTokens.length) return [];

  return SEARCH_DATA
    .map(item => ({ item, score: scoreResult(item, queryTokens) }))
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 8)
    .map(({ item }) => item);
}

// ── Search UI ────────────────────────────────────────────────
document.addEventListener('DOMContentLoaded', () => {
  const input   = document.getElementById('searchInput');
  const results = document.getElementById('searchResults');
  if (!input || !results) return;

  let debounceTimer;

  input.addEventListener('input', () => {
    clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      const q = input.value.trim();
      if (q.length < 2) {
        results.hidden = true;
        return;
      }

      const hits = search(q);
      if (!hits.length) {
        results.innerHTML = `<div class="search-no-results">No results for "<strong>${escapeHtml(q)}</strong>"</div>`;
        results.hidden = false;
        return;
      }

      const baseUrl = (window.SITE_BASEURL || '').replace(/\/$/, '');
      results.innerHTML = hits.map(hit => `
        <a href="${hit.url.startsWith('http') ? hit.url : baseUrl + hit.url}" class="search-result-item">
          <span class="search-result-section">${escapeHtml(hit.section)}</span>
          <span class="search-result-title">${highlight(escapeHtml(hit.title), q)}</span>
          <span class="search-result-preview">${getPreview(hit.body, q)}</span>
        </a>
      `).join('');
      results.hidden = false;
    }, 200);
  });

  // Keyboard navigation
  input.addEventListener('keydown', e => {
    if (e.key === 'Escape') {
      results.hidden = true;
      input.blur();
    }
    if (e.key === 'ArrowDown') {
      e.preventDefault();
      const first = results.querySelector('.search-result-item');
      first?.focus();
    }
  });

  results.addEventListener('keydown', e => {
    if (e.key === 'ArrowDown') {
      e.preventDefault();
      const focused = document.activeElement;
      const next = focused.nextElementSibling;
      next?.focus();
    }
    if (e.key === 'ArrowUp') {
      e.preventDefault();
      const focused = document.activeElement;
      const prev = focused.previousElementSibling;
      if (prev) prev.focus();
      else input.focus();
    }
    if (e.key === 'Escape') {
      results.hidden = true;
      input.focus();
    }
  });

  // Close on outside click
  document.addEventListener('click', e => {
    if (!input.contains(e.target) && !results.contains(e.target)) {
      results.hidden = true;
    }
  });
});

function escapeHtml(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function highlight(text, query) {
  const tokens = tokenize(query);
  let result = text;
  tokens.forEach(token => {
    const re = new RegExp(`(${token})`, 'gi');
    result = result.replace(re, '<mark style="background:rgba(79,70,229,.3);color:inherit;border-radius:2px;padding:0 1px">$1</mark>');
  });
  return result;
}

function getPreview(body, query) {
  const tokens = tokenize(query);
  const words = body.split(/\s+/);
  let bestIdx = 0;
  let bestScore = 0;
  words.forEach((w, i) => {
    const s = tokens.filter(t => w.toLowerCase().includes(t)).length;
    if (s > bestScore) { bestScore = s; bestIdx = i; }
  });
  const start = Math.max(0, bestIdx - 4);
  const end   = Math.min(words.length, bestIdx + 10);
  const snippet = words.slice(start, end).join(' ');
  return (start > 0 ? '…' : '') + highlight(escapeHtml(snippet), query) + (end < words.length ? '…' : '');
}
